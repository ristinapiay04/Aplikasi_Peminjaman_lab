    private void jTable1MouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTable1MouseClicked
        // TODO add your handling code here:
       
    int baris = jTable1.getSelectedRow();

    idPeminjaman =
            jTable1.getValueAt(baris, 0).toString();

    bgStatus.clearSelection();

    String status =
            jTable1.getValueAt(baris, 7).toString();

    if(status.equalsIgnoreCase("dipinjam")){

        jRadioButton1.setSelected(true);

    }else{

        jRadioButton2.setSelected(true);

    }

    }//GEN-LAST:event_jTable1MouseClicked

    private void jButton3ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton3ActionPerformed
        // TODO add your handling code here:
       
    try {

        if(idPeminjaman.equals("")){

            JOptionPane.showMessageDialog(
                    null,
                    "Pilih data terlebih dahulu");

            return;
        }

        String status = "";

        if(jRadioButton1.isSelected()){

            status = "Dipinjam";

        }else if(jRadioButton2.isSelected()){

            status = "Dikembalikan";

        }else{

            JOptionPane.showMessageDialog(
                    null,
                    "Pilih status");

            return;
        }

        Connection conn =
                class_koneksi.getConnection();

        String sql =
                "UPDATE tb_peminjaman "
                + "SET status_pengembalian=? "
                + "WHERE id_peminjam=?";

        PreparedStatement pst =
                conn.prepareStatement(sql);

        pst.setString(1, status);
        pst.setString(2, idPeminjaman);

        pst.executeUpdate();

        JOptionPane.showMessageDialog(
                null,
                "Status berhasil diubah");

        tampilData();

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                null,
                e.getMessage());

    }

    }//GEN-LAST:event_jButton3ActionPerformed

