    private void tampilData() {

    DefaultTableModel model = new DefaultTableModel();

    model.addColumn("ID");
    model.addColumn("Ruang");
    model.addColumn("Nama");
    model.addColumn("Identitas");
    model.addColumn("Tgl Pinjam");
    model.addColumn("Tgl Kembali");
    model.addColumn("Keperluan");
    model.addColumn("Status");

    try {

        Connection conn = class_koneksi.getConnection();

        String sql = "SELECT * FROM tb_peminjaman";

        PreparedStatement pst =
                conn.prepareStatement(sql);

        ResultSet rs = pst.executeQuery();

        while(rs.next()){

            model.addRow(new Object[]{

                rs.getString("id_peminjam"),
                rs.getString("ruang"),
                rs.getString("nama_peminjam"),
                rs.getString("identitas"),
                rs.getString("tgl_pinjam"),
                rs.getString("tgl_kembali"),
                rs.getString("keperluan"),
                rs.getString("status_pengembalian")

            });

        }

        jTable1.setModel(model);

    } catch (Exception e) {

        JOptionPane.showMessageDialog(
                null, e.getMessage());

    }
}
private void warnaStatus() {

    jTable1.setDefaultRenderer(
        Object.class,
        new javax.swing.table.DefaultTableCellRenderer() {

            @Override
            public java.awt.Component getTableCellRendererComponent(
                    javax.swing.JTable table,
                    Object value,
                    boolean isSelected,
                    boolean hasFocus,
                    int row,
                    int column) {

                java.awt.Component c =
                        super.getTableCellRendererComponent(
                                table, value,
                                isSelected,
                                hasFocus,
                                row,
                                column);

                String status =
                        table.getValueAt(row, 7).toString();

                if (!isSelected) {

                    if (status.equals("dipinjam")) {

                        c.setBackground(
                                java.awt.Color.PINK);

                    } else {

                        c.setBackground(
                                java.awt.Color.WHITE);

                    }
                }

                return c;
            }
        }
    );
}
