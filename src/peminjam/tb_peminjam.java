    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
      try {

    Connection conn = class_koneksi.getConnection();

    String sql = "INSERT INTO tb_peminjaman "
        + "(id_peminjam, ruang, nama_peminjam, identitas, "
        + "tgl_pinjam, tgl_kembali, keperluan, status_pengembalian) "
        + "VALUES (?,?,?,?,?,?,?,?)";

    PreparedStatement pst = conn.prepareStatement(sql);

    java.text.SimpleDateFormat sdf =
            new java.text.SimpleDateFormat("yyyy-MM-dd");

   pst.setString(1, jTextField1.getText()); // id_peminjam
pst.setString(2, jTextField2.getText()); // ruang
pst.setString(3, jTextField3.getText()); // nama
pst.setString(4, jTextField4.getText()); // identitas

pst.setString(5,
        sdf.format(jDateChooser2.getDate())); // tgl_pinjam

pst.setString(6,
        sdf.format(jDateChooser1.getDate())); // tgl_kembali

pst.setString(7,
        jTextArea1.getText()); // keperluan

pst.setString(8,
        jComboBox1.getSelectedItem().toString()); // status

    int hasil = pst.executeUpdate();

    if (hasil > 0) {

        JOptionPane.showMessageDialog(null,
                "Data berhasil disimpan");

        tampilData();
        bersih();
    }

} catch (Exception e) {

    JOptionPane.showMessageDialog(null,
            e.getMessage());

}
    }//GEN-LAST:event_jButton1ActionPerformed

