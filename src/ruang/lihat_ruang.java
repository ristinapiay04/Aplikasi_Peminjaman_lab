    private void jTextField1KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTextField1KeyReleased
        // TODO add your handling code here:
    DefaultTableModel model = new DefaultTableModel();

    model.addColumn("ID Ruang");
    model.addColumn("Nama Ruang");
    model.addColumn("Kapasitas");
    model.addColumn("Lokasi");
    model.addColumn("Status");

    try {

        Connection conn = class_koneksi.getConnection();

        String keyword = jTextField1.getText();

        String sql = "SELECT * FROM tb_ruang WHERE "
                + "id_ruang LIKE ? OR "
                + "nama_ruang LIKE ? OR "
                + "kapasitas LIKE ? OR "
                + "lokasi LIKE ? OR "
                + "status_ruang LIKE ?";

        PreparedStatement pst = conn.prepareStatement(sql);

        for (int i = 1; i <= 5; i++) {
            pst.setString(i, "%" + keyword + "%");
        }

        ResultSet rs = pst.executeQuery();

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getString("id_ruang"),
                rs.getString("nama_ruang"),
                rs.getString("kapasitas"),
                rs.getString("lokasi"),
                rs.getString("status_ruang")
            });

        }

        jTable1.setModel(model);

    } catch (Exception e) {

        javax.swing.JOptionPane.showMessageDialog(
                null, e.getMessage());

    }
    }//GEN-LAST:event_jTextField1KeyReleased

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        try {

    String html = "<html>"
            + "<head>"
            + "<title>Data Ruang</title>"
            + "<style>"
            + "table{border-collapse:collapse;width:100%;}"
            + "th,td{border:1px solid black;padding:8px;text-align:left;}"
            + "th{background:#cccccc;}"
            + "</style>"
            + "</head>"
            + "<body>";

    html += "<h2 align='center'>LAPORAN DATA RUANG</h2>";

    html += "<table>";
    html += "<tr>"
            + "<th>ID Ruang</th>"
            + "<th>Nama Ruang</th>"
            + "<th>Kapasitas</th>"
            + "<th>Lokasi</th>"
            + "<th>Status Ruang</th>"
            + "</tr>";

    for (int i = 0; i < jTable1.getRowCount(); i++) {

        html += "<tr>";

        for (int j = 0; j < jTable1.getColumnCount(); j++) {

            html += "<td>"
                    + jTable1.getValueAt(i, j)
                    + "</td>";

        }

        html += "</tr>";
    }

    html += "</table>";
    html += "</body></html>";

    File file = new File("laporan_ruang.html");

    try (FileWriter fw = new FileWriter(file)) {
    fw.write(html);
}

    Desktop.getDesktop().browse(file.toURI());

} catch (Exception e) {

    JOptionPane.showMessageDialog(null,
            "Gagal membuat laporan : "
            + e.getMessage());

}
    }//GEN-LAST:event_jButton2ActionPerformed

