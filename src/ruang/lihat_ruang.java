   private void tampilData() {

    DefaultTableModel model = new DefaultTableModel();

    model.addColumn("ID Ruang");
    model.addColumn("Nama Ruang");
    model.addColumn("Kapasitas");
    model.addColumn("Lokasi");
    model.addColumn("Status");

    try {

        Connection conn = class_koneksi.getConnection();

        String sql = "SELECT * FROM tb_ruang";

        PreparedStatement pst = conn.prepareStatement(sql);
        ResultSet rs = pst.executeQuery();

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getString("id_ruang"),
                rs.getString("nama_ruang"),
                rs.getString("kapasitas"),
                rs.getString("lokasi"),
                rs.getString("status_ruang")
            });

        }

        jTable1.setModel(model);

   }catch(Exception e){

        JOptionPane.showMessageDialog(
                null,e.getMessage());

    }
}
