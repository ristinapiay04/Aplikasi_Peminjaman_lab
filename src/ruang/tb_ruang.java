    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
    int baris = jTable1.getSelectedRow();

if (baris == -1) {
    JOptionPane.showMessageDialog(null,
            "Pilih data terlebih dahulu");
    return;
}

try {

    Connection conn = class_koneksi.getConnection();

    String id = model.getValueAt(baris, 0).toString();

    String sql = "DELETE FROM tb_ruang WHERE id_ruang=?";

    PreparedStatement pst = conn.prepareStatement(sql);

    pst.setString(1, id);

    pst.executeUpdate();

    JOptionPane.showMessageDialog(null,
            "Data berhasil dihapus");

    tampilData();
    bersih();

}catch(Exception e){

        JOptionPane.showMessageDialog(
                null,e.getMessage());

    }
    }//GEN-LAST:event_jButton2ActionPerformed

    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        try {

    Connection conn = class_koneksi.getConnection();

    String sql = "INSERT INTO tb_ruang "
        + "(id_ruang, nama_ruang, kapasitas, lokasi, status_ruang) "
        + "VALUES (?, ?, ?, ?, ?)";
    PreparedStatement pst = conn.prepareStatement(sql);

pst.setString(1, jTextField1.getText());
pst.setString(2, jTextField2.getText());
pst.setInt(3, Integer.parseInt(jTextField3.getText()));
pst.setString(4, jTextField4.getText());
pst.setString(5, jComboBox1.getSelectedItem().toString());
    int hasil = pst.executeUpdate();

if (hasil > 0) {
    JOptionPane.showMessageDialog(null,
            "Data berhasil disimpan");

    tampilData();
    bersih();
}

}catch(Exception e){

        JOptionPane.showMessageDialog(
                null,e.getMessage());

    }
    }//GEN-LAST:event_jButton1ActionPerformed

