    private void tampilData() {

    model.setRowCount(0);

    try {

        Connection conn = class_koneksi.getConnection();

        String sql = "SELECT * FROM tb_ruang";

        PreparedStatement pst = conn.prepareStatement(sql);

        java.sql.ResultSet rs = pst.executeQuery();

        while (rs.next()) {

            model.addRow(new Object[]{
                rs.getString("id_ruang"),
                rs.getString("nama_ruang"),
                rs.getString("kapasitas"),
                rs.getString("lokasi"),
                rs.getString("status_ruang")
            });

        }

    }catch(Exception e){

        JOptionPane.showMessageDialog(
                null,e.getMessage());

    }
}

