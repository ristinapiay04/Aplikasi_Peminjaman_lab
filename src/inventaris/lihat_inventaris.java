    private void jTextField1KeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_jTextField1KeyReleased
        // TODO add your handling code here:
        DefaultTableModel model =
        new DefaultTableModel();

        model.addColumn("ID");
        model.addColumn("ID Ruang");
        model.addColumn("Nama");
        model.addColumn("Identitas");
        model.addColumn("Tgl Pinjam");
        model.addColumn("Tgl Kembali");
        model.addColumn("Keperluan");
        model.addColumn("Status");

        try {

            Connection conn =
            class_koneksi.getConnection();

            String keyword =
            jTextField1.getText();

            String sql =
            "SELECT * FROM tb_peminjaman WHERE "
            + "id_peminjam LIKE ? OR "
            + "id_ruang LIKE ? OR "
            + "nama_peminjam LIKE ? OR "
            + "identitas LIKE ? OR "
            + "status_pengembalian LIKE ?";

            PreparedStatement pst =
            conn.prepareStatement(sql);

            for(int i=1;i<=5;i++){
                pst.setString(i,
                    "%" + keyword + "%");
            }

            ResultSet rs =
            pst.executeQuery();

            while(rs.next()){

                model.addRow(new Object[]{

                    rs.getString("id_peminjam"),
                    rs.getString("id_ruang"),
                    rs.getString("nama_peminjam"),
                    rs.getString("identitas"),
                    rs.getString("tgl_pinjam"),
                    rs.getString("tgl_kembali"),
                    rs.getString("keperluan"),
                    rs.getString("status_pengembalian")

                });

            }

            jTable1.setModel(model);

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                null, e.getMessage());

        }
    }//GEN-LAST:event_jTextField1KeyReleased

