   private void tampilData(){

    model.setRowCount(0);

    try{

        Connection conn =
                class_koneksi.getConnection();

        String sql =
                "SELECT * FROM tb_inventaris";

        PreparedStatement pst =
                conn.prepareStatement(sql);

        ResultSet rs =
                pst.executeQuery();

        while(rs.next()){

            model.addRow(new Object[]{

                rs.getString("id_inventaris"),
                rs.getString("nama_barang"),
                rs.getString("jumlah"),
                rs.getString("kondisi"),
                rs.getString("lokasi")

            });

        }

    }catch(Exception e){

        JOptionPane.showMessageDialog(
                null,e.getMessage());

    }
}
